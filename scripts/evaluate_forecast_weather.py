"""Recompute the forecast-weather metrics and report from saved predictions only.

    python scripts/evaluate_forecast_weather.py

Reads results/forecast_weather_predictions.parquet + results/forecast_weather_run_metadata.json
(+ results/run_metadata.json for the pre-2023 high-price threshold). Needs no download and no model.
If results/forecast_weather_metrics.json already exists, the recomputed metrics must equal it
(tolerance 1e-6) or the script exits 1; otherwise it writes it.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scripts.evaluate_predictions import TOLERANCE, max_abs_diff  # noqa: E402
from src.evaluation import daily_loss, diebold_mariano, summarize  # noqa: E402

REF = "naive_24h"
NO_FORECAST = ["naive_24h", "naive_168h", "xgb_B", "xgb_C_oracle_temp"]
MODELS = ["naive_24h", "naive_168h", "xgb_B", "xgb_B_matched_window", "xgb_D1_train_actual", "xgb_D1_train_fc",
          "xgb_D2_train_actual", "xgb_D2_train_fc", "xgb_C_oracle_temp"]
LABEL = {
    "naive_24h": "Naive: same hour yesterday [reference]",
    "naive_168h": "Seasonal naive: same hour last week",
    "xgb_B": "XGBoost B (prices+calendar+load), no weather, full history",
    "xgb_B_matched_window": "XGBoost B, no weather, trained on the same dates as forecast-trained models [control]",
    "xgb_D1_train_actual": "XGBoost + forecast temp (1-day lead), (a) trained on actual temp",
    "xgb_D1_train_fc": "XGBoost + forecast temp (1-day lead), (b) trained on forecasts",
    "xgb_D2_train_actual": "XGBoost + forecast temp (2-day lead, sensitivity), (a) trained on actual temp",
    "xgb_D2_train_fc": "XGBoost + forecast temp (2-day lead, sensitivity), (b) trained on forecasts",
    "xgb_C_oracle_temp": "XGBoost + target-day ACTUAL temp (oracle, upper bound)"}
PAIRS = [("xgb_D1_train_actual", "xgb_B_matched_window"), ("xgb_D1_train_fc", "xgb_B_matched_window"),
         ("xgb_D1_train_actual", "xgb_B"), ("xgb_D2_train_actual", "xgb_D1_train_actual"),
         ("xgb_C_oracle_temp", "xgb_D1_train_actual")]


def compute(df: pd.DataFrame, hi: float) -> dict:
    common = df.dropna(subset=["y"] + MODELS)
    s = summarize(df, MODELS, ref=REF, high_price_threshold=hi)
    out = {"comparison_vs_yesterday_naive": s,
           "all_730_days_no_forecast_models": summarize(df, NO_FORECAST, ref=REF, high_price_threshold=hi),
           "dm_pairs": {}}
    for a, b in PAIRS:
        out["dm_pairs"][f"{a} vs {b}"] = diebold_mariano(daily_loss(common, a), daily_loss(common, b))
    return out


def table(block: dict, models: list[str]) -> list[str]:
    rows = ["| model | MAE ($/MWh) | RMSE | bias | rMAE vs yesterday-naive |", "|---|---|---|---|---|"]
    for m in models:
        r = block[m]
        rows.append(f"| {LABEL[m]} | {r['MAE']:.2f} | {r['RMSE']:.2f} | {r['bias']:+.2f} | {r['rMAE']:.3f} |")
    return rows


def main():
    res = ROOT / "results"
    df = pd.read_parquet(res / "forecast_weather_predictions.parquet")
    meta = json.loads((res / "forecast_weather_run_metadata.json").read_text())
    hi = json.loads((res / "run_metadata.json").read_text())["high_price_threshold_pre2023_p95"]
    m = json.loads(json.dumps(compute(df, hi)))
    target = res / "forecast_weather_metrics.json"
    diff = 0.0
    if target.exists():
        diff = max_abs_diff(m, json.loads(target.read_text()))
    same = diff <= TOLERANCE
    print(f"max abs difference vs saved metrics: {diff:.3g} (tolerance {TOLERANCE}) -> {'OK' if same else 'MISMATCH'}")
    if not target.exists():
        target.write_text(json.dumps(m, indent=2))

    s, w = m["comparison_vs_yesterday_naive"], meta["weather"]
    ex = meta["excluded_days_missing_forecast"]
    L = ["# Forecast-weather experiment: NYISO N.Y.C. day-ahead price (generated by scripts/evaluate_forecast_weather.py)", "",
         "**Question.** The earlier backtest's best model used the target day's ACTUAL temperature (a perfect-foresight oracle). "
         "Does weather still help when only a day-ahead FORECAST is available?", "",
         f"**Setup.** Same walk-forward protocol and frozen XGBoost hyperparameters as `results/backtest_report.md` "
         f"({meta['xgb_params_frozen_from_run_backtest']}, chosen on 2022 only using the oracle feature set C; not retuned for forecast weather). Weather = GFS (`{meta['weather_model']}`) "
         "2 m temperature from the Open-Meteo Previous Runs API issued 1 day (primary) or 2 days (sensitivity) before the valid hour. "
         f"{meta['n_excluded_days']} test days ({ex[0]} to {ex[-1]}) have a missing forecast hour (one upstream outage) and are "
         f"excluded for every model below; {s['n_days']} days / {s['n_points']:,} hourly points remain, identical for all models. "
         "Nothing is imputed and actuals never fill forecast gaps.", "",
         "**Variants.** (a) trained on ACTUAL temperature, predicted with the forecast; (b) trained on archived FORECASTS. "
         "The control is the no-weather model B retrained on exactly the dates (b) can train on.", "",
         "**Limits.** One zone, one weather point, GFS only, one 2-year window, one frozen hyperparameter set. "
         "The run initialisation time behind `previous_day1` is undocumented, so the 2-day-lead rows are the leakage-safe check. "
         "No gas, outage or generation-mix data. A retrospective backtest, not a trading result.", "",
         "## Forecast quality (test days, hours with both forecast and actual)", "",
         "| lead | MAE (deg C) | bias | RMSE | hours |", "|---|---|---|---|---|"]
    for k in ("previous_day1", "previous_day2"):
        q = w[k]["forecast_minus_actual_temp_C"]
        L.append(f"| {k[-1]} day | {q['MAE']:.2f} | {q['bias']:+.2f} | {q['RMSE']:.2f} | {q['n_hours']:,} |")
    L += ["", "## Overall (all models on identical points; rMAE reference = yesterday-naive)", ""] + table(s["overall"], MODELS)
    L += ["", "## Diebold-Mariano against yesterday-naive (daily mean absolute error, HAC lag 7)", "",
          "| model | mean daily MAE difference | DM stat | p-value |", "|---|---|---|---|"]
    for k, r in s["dm_vs_ref"].items():
        L.append(f"| {LABEL[k]} | {r['mean_diff']:+.3f} | {r['stat']:+.2f} | {r['p_value']:.3g} |")
    L += ["", "## Selected pairwise comparisons (first model minus second; negative = first is better)", "",
          "| pair | mean daily MAE difference | DM stat | p-value |", "|---|---|---|---|"]
    for k, r in m["dm_pairs"].items():
        L.append(f"| {k} | {r['mean_diff']:+.3f} | {r['stat']:+.2f} | {r['p_value']:.3g} |")
    L += ["", "With 707 serially correlated daily losses, treat p-values as indicative.", "", "## By year (MAE)", "",
          "| year | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for y, b in s["by_year"].items():
        L.append(f"| {y} | " + " | ".join(f"{b[k]['MAE']:.2f}" for k in MODELS) + " |")
    hp = s["high_price_hours"]
    L += ["", f"## High-price hours (>= {hp['threshold']:.1f} $/MWh, 95th percentile of 2019-2022; n={hp['n']})", ""] + table(hp["metrics"], MODELS)
    a = m["all_730_days_no_forecast_models"]
    L += ["", f"## All {a['n_days']} test days, models that need no forecast (for reference; includes the excluded days)", ""] + table(a["overall"], NO_FORECAST)
    L += ["", "Weather data by Open-Meteo.com (CC BY 4.0). Raw API responses are not committed."]
    (res / "forecast_weather_report.md").write_text("\n".join(L) + "\n")
    sys.exit(0 if same else 1)


if __name__ == "__main__":
    main()
