"""Recompute operational-origin metrics, the serving-eligibility decision and the report.

    python scripts/evaluate_operational.py

Reads results/operational_predictions.parquet + operational_run_metadata.json (committed). No download,
no model fit. If results/operational_metrics.json exists the recomputed metrics must match it
(tolerance 1e-6) or the script exits 1. Writes results/operational_decision.json, which the serving
registry reads: it is the evidence a model needs before it may serve (rule in run_operational_backtest.py).
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from scripts.evaluate_predictions import TOLERANCE, max_abs_diff  # noqa: E402
from src.evaluation import block_bootstrap_ci, daily_loss, diebold_mariano, summarize  # noqa: E402

REF = "naive_24h"
MODELS = ["naive_24h", "xgb_OB", "xgb_OB_matched_window", "xgb_OD_train_actual", "xgb_OD_train_fc"]
WEATHER_MODELS = {"xgb_OD_train_actual", "xgb_OD_train_fc"}
LABEL = {"naive_24h": "Baseline: same hour of day D [reference]",
         "xgb_OB": "XGBoost OB (prices, calendar, load through D-1), no weather",
         "xgb_OB_matched_window": "XGBoost OB, trained on the same dates as the forecast-trained model [control]",
         "xgb_OD_train_actual": "XGBoost OD (+ forecast temp, 48 h lead), (a) trained on actual temp",
         "xgb_OD_train_fc": "XGBoost OD (+ forecast temp, 48 h lead), (b) trained on forecasts"}
RULE = ("eligible iff, vs the baseline on the common days: (1) 95% block-bootstrap CI of the daily MAE "
        "difference is entirely < 0, (2) Diebold-Mariano p < 0.05, (3) mean daily MAE difference < 0 in "
        "every calendar year of the test window")


def compute(df: pd.DataFrame, hi: float) -> dict:
    d = df.dropna(subset=["y"] + MODELS)
    s = summarize(df, MODELS, ref=REF, high_price_threshold=hi)
    dates = d.index.get_level_values("date")
    base = daily_loss(d, REF)
    day_index = pd.DatetimeIndex(sorted(set(dates)))
    out = {"summary": s, "vs_baseline": {}, "mae_by_hour": {}}
    for m in MODELS:
        out["mae_by_hour"][m] = {int(h): float(v) for h, v in
                                 (d[m] - d["y"]).abs().groupby(level="hour").mean().items()}
        if m == REF:
            continue
        diff = daily_loss(d, m) - base
        ci = block_bootstrap_ci(diff, block=7, n_boot=2000, seed=0)
        dm = diebold_mariano(daily_loss(d, m), base)
        yearly = {str(y): float(diff[day_index.year == y].mean()) for y in sorted(set(day_index.year))}
        ok = bool(ci["hi"] < 0 and dm["p_value"] < 0.05 and all(v < 0 for v in yearly.values()))
        out["vs_baseline"][m] = {"mae_diff_ci": ci, "dm": dm, "mean_diff_by_year": yearly,
                                 "weather_dependent": m in WEATHER_MODELS, "eligible_to_serve": ok}
    elig = {m: v for m, v in out["vs_baseline"].items() if v["eligible_to_serve"]}
    best = min(elig, key=lambda m: s["overall"][m]["MAE"]) if elig else None
    out["decision"] = {"rule": RULE, "eligible_models": sorted(elig), "serving_candidate": best,
                       "if_none_eligible": "serve the baseline (same hour of day D)"}
    return out


def tbl(s):
    r = ["| model | MAE ($/MWh) | RMSE | bias | rMAE vs baseline |", "|---|---|---|---|---|"]
    for m in MODELS:
        x = s[m]
        r.append(f"| {LABEL[m]} | {x['MAE']:.2f} | {x['RMSE']:.2f} | {x['bias']:+.2f} | {x['rMAE']:.3f} |")
    return r


def main():
    res = ROOT / "results"
    df = pd.read_parquet(res / "operational_predictions.parquet")
    meta = json.loads((res / "operational_run_metadata.json").read_text())
    hi = json.loads((res / "run_metadata.json").read_text())["high_price_threshold_pre2023_p95"]
    m = json.loads(json.dumps(compute(df, hi)))
    target = res / "operational_metrics.json"
    diff = max_abs_diff(m, json.loads(target.read_text())) if target.exists() else 0.0
    same = diff <= TOLERANCE
    print(f"max abs difference vs saved metrics: {diff:.3g} (tolerance {TOLERANCE}) -> {'OK' if same else 'MISMATCH'}")
    if not target.exists():
        target.write_text(json.dumps(m, indent=2))
    (res / "operational_decision.json").write_text(json.dumps(m["decision"], indent=2))

    s, ex = m["summary"], meta["excluded_days_missing_forecast"]
    L = ["# Operational-origin backtest: NYISO N.Y.C. day-ahead price (generated by scripts/evaluate_operational.py)", "",
         "**Question.** Using only information available at 05:00 ET on day D (see `docs/operational-timing.md`), "
         "does any model beat the baseline of repeating the price of day D, so that it deserves to serve forecasts?", "",
         f"**Setup.** Features OB/OD exclude day-D load and observed temperature. Weather = GFS 48-hour-lead forecast "
         f"(Open-Meteo `previous_day2`). Hyperparameters chosen on 2022 only with these features "
         f"({meta['chosen_params']}). {meta['n_excluded_days']} days ({ex[0]} to {ex[-1]}) have a missing forecast hour and are "
         f"excluded for every model; {s['n_days']} days / {s['n_points']:,} hourly points remain. Nothing is imputed.", "",
         f"**Serving rule (fixed before the run):** {RULE}. If no model is eligible the system serves the baseline.", "",
         "**Limits.** One zone, one weather point, GFS only, one 2-year window. The live forecast available at the origin is "
         "related to, but not identical with, the archived 48-hour-lead proxy. A retrospective backtest, not a trading result.", "",
         "## Overall (identical points for all models)", ""] + tbl(s["overall"])
    L += ["", "## Difference vs baseline (daily mean absolute error; negative = better than baseline)", "",
          "| model | mean diff | 95% block-bootstrap CI | DM p | 2023 | 2024 | eligible to serve |", "|---|---|---|---|---|---|---|"]
    for k, v in m["vs_baseline"].items():
        c, y = v["mae_diff_ci"], v["mean_diff_by_year"]
        L.append(f"| {LABEL[k]} | {c['mean']:+.3f} | [{c['lo']:+.3f}, {c['hi']:+.3f}] | {v['dm']['p_value']:.3g} | "
                 f"{y.get('2023', float('nan')):+.3f} | {y.get('2024', float('nan')):+.3f} | **{'yes' if v['eligible_to_serve'] else 'no'}** |")
    dec = m["decision"]
    L += ["", f"**Decision:** serving candidate = `{dec['serving_candidate']}`; eligible = {dec['eligible_models'] or 'none'}. "
          f"If none: {dec['if_none_eligible']}.", "", "## By year (MAE)", "",
          "| year | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for y, b in s["by_year"].items():
        L.append(f"| {y} | " + " | ".join(f"{b[k]['MAE']:.2f}" for k in MODELS) + " |")
    hp = s["high_price_hours"]
    L += ["", f"## High-price hours (>= {hp['threshold']:.1f} $/MWh, 95th percentile of 2019-2022; n={hp['n']})", ""] + tbl(hp["metrics"])
    L += ["", "## MAE by hour of day (local hour)", "", "| hour | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for h in range(24):
        L.append(f"| {h} | " + " | ".join(f"{m['mae_by_hour'][k][str(h)]:.2f}" for k in MODELS) + " |")
    L += ["", "Weather data by Open-Meteo.com (CC BY 4.0). Raw API responses are not committed."]
    (res / "operational_report.md").write_text("\n".join(L) + "\n")
    sys.exit(0 if same else 1)


if __name__ == "__main__":
    main()
