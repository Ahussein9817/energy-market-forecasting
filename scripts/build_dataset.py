"""Download NYISO prices + load and Open-Meteo temperature; write parquet + quality report.

    python scripts/build_dataset.py --start 2019-01 --end 2024-12

Raw zips are cached in data/raw/ and parquet outputs go to data/processed/ (both gitignored;
public data is re-downloadable and not redistributed here). Writes docs/data-quality-report.md.
"""
import argparse
import logging
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src import data_loader as dl  # noqa: E402


def quality_report(prices: pd.DataFrame, load: pd.DataFrame, wx: pd.DataFrame, start, end) -> str:
    L = [f"# Data quality report ({start} to {end}, generated by scripts/build_dataset.py)", ""]
    exp_hours = int((pd.Timestamp(end) + pd.offsets.MonthEnd(0) + pd.Timedelta(days=1)
                     - pd.Timestamp(start)).total_seconds() // 3600)
    L += [f"Expected hours in range (UTC): {exp_hours:,}", "",
          "## Day-ahead LBMP by zone", "", "| zone | rows | missing hours | duplicate timestamps | negative-price hours | min | max | median |",
          "|---|---|---|---|---|---|---|---|"]
    for z, g in prices.groupby("zone"):
        L.append(f"| {z} | {len(g):,} | {exp_hours - g['timestamp_utc'].nunique():,} | "
                 f"{int(g['timestamp_utc'].duplicated().sum())} | {int((g['lbmp'] < 0).sum())} | "
                 f"{g['lbmp'].min():.2f} | {g['lbmp'].max():.2f} | {g['lbmp'].median():.2f} |")
    L += ["", "## Integrated actual load by zone (MW)", "", "| zone | rows | missing hours | duplicates | null | min | max |",
          "|---|---|---|---|---|---|---|"]
    for z, g in load.groupby("zone"):
        L.append(f"| {z} | {len(g):,} | {exp_hours - g['timestamp_utc'].nunique():,} | "
                 f"{int(g['timestamp_utc'].duplicated().sum())} | {int(g['load_mw'].isna().sum())} | "
                 f"{g['load_mw'].min():.1f} | {g['load_mw'].max():.1f} |")
    L += ["", "## Temperature (Open-Meteo, NYC point)", "",
          f"rows {len(wx):,}; missing hours {exp_hours - wx['timestamp_utc'].nunique():,}; "
          f"null values {int(wx['temp_c'].isna().sum())}; range {wx['temp_c'].min():.1f} to {wx['temp_c'].max():.1f} C", ""]
    L += ["## Notes", "",
          "- Prices are day-ahead (market-clearing) zonal LBMP in $/MWh, not real-time prices.",
          "- Negative prices occur in some zones (H Q, NORTH, HUD VL, CAPITL), not in N.Y.C.; even where prices stay positive, hours with very low prices make percentage-error metrics (MAPE) unstable, so MAE/RMSE (and scaled errors) are the primary metrics.",
          "- NYISO price files have local timestamps without a timezone column; DST is resolved from row order (tested).",
          "- Zones include external proxies (e.g. H Q, NPX, O H, PJM) that have no load series.",
          "- Weather is a single NYC point, a coarse proxy for statewide conditions."]
    return "\n".join(L) + "\n"


def main():
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", default="2019-01")
    ap.add_argument("--end", default="2024-12")
    a = ap.parse_args()
    raw, proc = ROOT / "data/raw", ROOT / "data/processed"
    proc.mkdir(parents=True, exist_ok=True)
    prices, loads = [], []
    for y, m in dl.months(a.start, a.end):
        prices.append(dl.parse_dam_lbmp(dl.download_month("damlbmp_zone", y, m, raw)))
        loads.append(dl.parse_integrated_load(dl.download_month("palIntegrated", y, m, raw)))
        logging.info("%d-%02d ok", y, m)
    prices = pd.concat(prices, ignore_index=True).sort_values(["zone", "timestamp_utc"])
    load = pd.concat(loads, ignore_index=True).sort_values(["zone", "timestamp_utc"])
    end_day = (pd.Period(a.end, "M").end_time).strftime("%Y-%m-%d")
    wx = dl.fetch_open_meteo(f"{a.start}-01", end_day)
    prices.to_parquet(proc / "nyiso_dam_lbmp.parquet", index=False)
    load.to_parquet(proc / "nyiso_load.parquet", index=False)
    wx.to_parquet(proc / "nyc_temperature.parquet", index=False)
    (ROOT / "docs" / "data-quality-report.md").write_text(quality_report(prices, load, wx, a.start, a.end))
    print("done")


if __name__ == "__main__":
    main()
