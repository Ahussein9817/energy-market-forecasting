"""Recompute all backtest metrics and the markdown report from the saved predictions only.

    python scripts/evaluate_predictions.py

Reads results/predictions_test.parquet + results/run_metadata.json (committed). Needs no data
download and no model. Verifies the recomputed metrics equal results/backtest_metrics.json.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src.evaluation import summarize  # noqa: E402

MODELS = ["naive_24h", "naive_168h", "sarimax", "sarimax_x_oracle_temp",
          "xgb_A", "xgb_B", "xgb_C_oracle_temp"]
LABEL = {"naive_24h": "Naive (same hour yesterday)", "naive_168h": "Seasonal naive (same hour last week) [reference]",
         "sarimax": "SARIMAX(1,0,1)(1,0,1,24), 56-day window", "sarimax_x_oracle_temp": "SARIMAX + target-day temperature (oracle)",
         "xgb_A": "XGBoost, prices + calendar (A)", "xgb_B": "XGBoost, + load lags (B)",
         "xgb_C_oracle_temp": "XGBoost, + target-day temperature (C, oracle)"}


def table(block: dict) -> list[str]:
    rows = ["| model | MAE ($/MWh) | RMSE | bias | rMAE vs seasonal naive | rRMSE |", "|---|---|---|---|---|---|"]
    for m in MODELS:
        r = block[m]
        rows.append(f"| {LABEL[m]} | {r['MAE']:.2f} | {r['RMSE']:.2f} | {r['bias']:+.2f} | {r['rMAE']:.3f} | {r['rRMSE']:.3f} |")
    return rows


def max_abs_diff(a, b):
    """Largest absolute numeric difference between two nested JSON-like structures
    (inf if their structure or non-numeric values differ)."""
    if isinstance(a, dict) and isinstance(b, dict):
        if a.keys() != b.keys():
            return float("inf")
        return max((max_abs_diff(a[k], b[k]) for k in a), default=0.0)
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return float("inf")
        return max((max_abs_diff(x, y) for x, y in zip(a, b)), default=0.0)
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
        if a != a and b != b:  # both NaN
            return 0.0
        return abs(a - b)
    return 0.0 if a == b else float("inf")


TOLERANCE = 1e-6  # cross-platform float differences, in $/MWh or unitless ratios


def main():
    res = ROOT / "results"
    df = pd.read_parquet(res / "predictions_test.parquet")
    meta = json.loads((res / "run_metadata.json").read_text())
    s = summarize(df, MODELS, ref="naive_168h", high_price_threshold=meta["high_price_threshold_pre2023_p95"])
    s24 = summarize(df, MODELS, ref="naive_24h", high_price_threshold=meta["high_price_threshold_pre2023_p95"])
    (res / "backtest_metrics_vs_naive24h.json").write_text(json.dumps(s24, indent=2))
    saved = json.loads((res / "backtest_metrics.json").read_text())
    # round-trip through JSON so types match the saved file, then compare with a tolerance
    diff = max_abs_diff(json.loads(json.dumps(s)), saved)
    same = diff <= TOLERANCE
    print(f"max abs difference between recomputed and saved metrics: {diff:.3g} (tolerance {TOLERANCE}) -> {'OK' if same else 'MISMATCH'}")
    L = ["# Day-ahead price forecasting backtest: NYISO N.Y.C. zone (generated by scripts/evaluate_predictions.py)", "",
         f"Test period {meta['test_start']} to {meta['test_end']} ({s['n_days']} days, {s['n_points']:,} hourly points). "
         "Target: day-ahead LBMP, $/MWh. Hyperparameters chosen on 2022 only "
         f"({meta['chosen_params']}). Every model is scored on exactly the same points. "
         f"SARIMAX estimation failures: {meta['sarimax_failures']}.", "",
         "**Read with care.** Models marked *oracle* use the target day's actual temperature (a perfect weather forecast) and are "
         "optimistic. No natural-gas, generation-mix or outage data is used. This is a retrospective backtest on one zone and "
         "one 2-year window, not a trading result.", "", "## Overall", ""] + table(s["overall"])
    L += ["", "## Against the strongest simple benchmark: same hour yesterday",
          "", "The 168-hour seasonal naive is a weak reference here (day-to-day persistence beats weekly persistence), so the "
          "rMAE column above flatters every model. The fair test is yesterday's same-hour price:", "",
          "| model | MAE | rMAE vs yesterday-naive | DM stat vs yesterday-naive | p-value |", "|---|---|---|---|---|"]
    for m in MODELS:
        if m == "naive_24h":
            continue
        r, d = s24["overall"][m], s24["dm_vs_ref"][m]
        L.append(f"| {LABEL[m]} | {r['MAE']:.2f} | {r['rMAE']:.3f} | {d['stat']:+.2f} | {d['p_value']:.3g} |")
    L += ["", "Negative DM statistic = lower daily MAE than yesterday-naive. Only the oracle-temperature XGBoost clearly beats it on MAE. "
          "SARIMAX (no oracle) is slightly WORSE on MAE (though better on RMSE: it forecasts spikes less badly in squared terms), and "
          "XGBoost A and B are statistically indistinguishable from it.", "", "## By year", ""]
    for y, b in s["by_year"].items():
        L += [f"### {y}", ""] + table(b) + [""]
    hp = s["high_price_hours"]
    L += [f"## High-price hours (day-ahead price >= {hp['threshold']:.1f} $/MWh, the 95th percentile of 2019-2022; n={hp['n']})", ""] + table(hp["metrics"])
    L += ["", "## Diebold-Mariano vs seasonal naive (daily mean absolute error, HAC lag 7)", "",
          "| model | mean daily MAE difference ($/MWh) | DM stat | p-value |", "|---|---|---|---|"]
    for m, r in s["dm_vs_ref"].items():
        L.append(f"| {LABEL[m]} | {r['mean_diff']:+.3f} | {r['stat']:.2f} | {r['p_value']:.3g} |")
    L += ["", "Negative difference = lower error than seasonal naive. With 730 daily losses and heavy serial correlation, treat p-values as indicative.",
          "", "## By quarter (MAE)", "", "| quarter | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for q, b in s["by_quarter"].items():
        L.append(f"| {q} | " + " | ".join(f"{b[m]['MAE']:.2f}" for m in MODELS) + " |")
    (res / "backtest_report.md").write_text("\n".join(L) + "\n")
    sys.exit(0 if same else 1)


if __name__ == "__main__":
    main()
